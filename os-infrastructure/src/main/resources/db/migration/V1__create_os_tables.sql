CREATE TABLE ordens_de_servico (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                    UUID         NOT NULL UNIQUE,
    cliente_uuid            UUID         NOT NULL,
    veiculo_uuid            UUID         NOT NULL,
    descricao_problema      VARCHAR(500) NOT NULL,
    status                  VARCHAR(30)  NOT NULL,
    status_entrega          VARCHAR(30)  NOT NULL DEFAULT 'NAO_LIBERADA',
    motivo_cancelamento     VARCHAR(500),
    orcamento_uuid          UUID,
    data_aprovacao          TIMESTAMP,
    mecanico_uuid           UUID,
    execucao_iniciada_em    TIMESTAMP,
    execucao_finalizada_em  TIMESTAMP,
    observacao_execucao     VARCHAR(1000),
    entregue_em             TIMESTAMP,
    recebido_por            VARCHAR(200),
    version                 BIGINT       NOT NULL DEFAULT 0,
    created_at              TIMESTAMP    NOT NULL,
    updated_at              TIMESTAMP,
    created_by              UUID,
    updated_by              UUID,
    deleted_at              TIMESTAMP,
    is_active               BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE INDEX idx_os_status_active ON ordens_de_servico (status, is_active);
CREATE INDEX idx_os_cliente ON ordens_de_servico (cliente_uuid);
CREATE INDEX idx_os_veiculo ON ordens_de_servico (veiculo_uuid);

CREATE TABLE os_itens (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid            UUID           NOT NULL UNIQUE,
    os_id           BIGINT         NOT NULL REFERENCES ordens_de_servico(id) ON DELETE CASCADE,
    referencia_uuid UUID           NOT NULL,
    tipo            VARCHAR(20)    NOT NULL,
    descricao       VARCHAR(255)   NOT NULL,
    valor_unitario  NUMERIC(15, 2) NOT NULL,
    quantidade      BIGINT         NOT NULL,
    created_at      TIMESTAMP      NOT NULL,
    updated_at      TIMESTAMP,
    created_by      UUID,
    updated_by      UUID,
    deleted_at      TIMESTAMP,
    is_active       BOOLEAN        NOT NULL DEFAULT TRUE
);

CREATE INDEX idx_os_itens_os_id ON os_itens (os_id);

CREATE TABLE processed_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id     UUID         NOT NULL UNIQUE,
    tipo_evento   VARCHAR(100) NOT NULL,
    processado_em TIMESTAMP    NOT NULL
);

CREATE TABLE outbox_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id      UUID         NOT NULL UNIQUE,
    aggregate_id  UUID         NOT NULL,
    event_type    VARCHAR(100) NOT NULL,
    payload       TEXT         NOT NULL,
    status        VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    attempts      INT          NOT NULL DEFAULT 0,
    last_error    TEXT,
    created_at    TIMESTAMP    NOT NULL,
    published_at  TIMESTAMP
);

CREATE INDEX idx_outbox_status_created ON outbox_events (status, created_at);
